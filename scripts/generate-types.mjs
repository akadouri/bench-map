#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
import { resolve } from "node:path";
import process from "node:process";

const root = resolve(new URL("..", import.meta.url).pathname);
const schemaFiles = (await readdir(resolve(root, "src/schemas")))
  .filter((file) => file.endsWith(".schema.json"))
  .sort()
  .map((file) => `src/schemas/${file}`);
const generated = [];
const versions = {};
const fields = {};
const required = {};

for (const relative of schemaFiles) {
  const file = resolve(root, relative);
  const source = await readFile(file, "utf8");
  const schema = JSON.parse(source);
  const name = schema.title;
  versions[name] = String(schema.schemaVersion ?? "");
  fields[name] = Object.keys(schema.properties ?? {});
  required[name] = schema.required ?? [];
  const hash = createHash("sha256").update(source).digest("hex");
  generated.push(`// ${relative} | schemaVersion: ${versions[name]} | derived: ${Boolean(schema.derived)} | sha256: ${hash}`);
  let types = (await compile(schema, name, { bannerComment: "", style: { semi: true } })).trim();
  const aliases = [...types.matchAll(/export type (\w+) =/g)].map((match) => match[1]);
  for (const alias of aliases) {
    types = types.replaceAll(new RegExp(`\\b${alias}\\b`, "g"), `${name}${alias}`);
  }
  generated.push(types);
}

generated.push(`export const SCHEMA_VERSIONS = ${JSON.stringify(versions, null, 2)} as const;`);
generated.push(`export const SCHEMA_FIELDS = ${JSON.stringify(fields, null, 2)} as const;`);
generated.push(`export const SCHEMA_REQUIRED = ${JSON.stringify(required, null, 2)} as const;`);
const output = `// AUTO-GENERATED by scripts/generate-types.mjs. Do not edit manually.\n\n${generated.join("\n\n")}\n`;
const target = resolve(root, "src/types/generated.ts");

if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8").catch(() => "");
  if (existing !== output) {
    console.error(`${target} is out of date. Run npm run generate:types.`);
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
}
